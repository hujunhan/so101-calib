def write_board_page(path: Path = TOOLS / "ipad_charuco.html") -> Path:
    img = ch.board_image()
    ok, png = cv2.imencode(".png", img)
    path.write_text(
        PAGE.format(
            sx=ch.SQUARES_X,
            sy=ch.SQUARES_Y,
            sq_mm=ch.SQUARE_M * 1000,
            ppi=ch.IPAD_PPI,
            w=img.shape[1],
            h=img.shape[0],
            png=base64.b64encode(png.tobytes()).decode(),
        )
    )
    return path


# -- capture -------------------------------------------------------------------------------------------------
def open_camera(name: str) -> cv2.VideoCapture:
    from so101_core.config import DeviceConfig

    key, fourcc, (w, h) = CAMERAS[name]
    cap = cv2.VideoCapture(DeviceConfig.load().cameras[key], cv2.CAP_V4L2)
    cap.set(cv2.CAP_PROP_FOURCC, cv2.VideoWriter_fourcc(*fourcc))
    cap.set(cv2.CAP_PROP_FRAME_WIDTH, w)
    cap.set(cv2.CAP_PROP_FRAME_HEIGHT, h)
    cap.set(cv2.CAP_PROP_FPS, 30)
    if not cap.isOpened():
        raise SystemExit(f"cannot open the {name} camera")
    return cap


def halves(frame: np.ndarray, name: str) -> list[np.ndarray]:
    """The images to calibrate: the whole frame, or the ZED's left and right eye."""
    if name == "zed":
        w = frame.shape[1] // 2
        return [frame[:, :w], frame[:, w:]]
    return [frame]


def pose_descriptor(view: ch.View, size: tuple[int, int]) -> np.ndarray:
    """Where the board is (centre), how big, and how it is tilted (from a homography): views far apart in
    this space constrain the intrinsics differently."""
    w, h = size
    c = view.img.mean(0) / [w, h]
    hull = cv2.convexHull(view.img.astype(np.float32))
    scale = np.sqrt(cv2.contourArea(hull) / (w * h))
    H, _ = cv2.findHomography(view.obj[:, :2], view.img)
    f = float(w)  # a rough focal length is enough to tell tilts apart
    Kinv = np.linalg.inv(np.array([[f, 0, w / 2], [0, f, h / 2], [0, 0, 1.0]]))
    r1, r2 = Kinv @ H[:, 0], Kinv @ H[:, 1]
    n = np.cross(r1 / np.linalg.norm(r1), r2 / np.linalg.norm(r2))
    n /= np.linalg.norm(n)
    tilt = np.abs(n[:2])  # 0 = facing the camera
    return np.concatenate([c, [scale], tilt])


def capture(name: str) -> Path:
    cap = open_camera(name)
    out = CAPTURES / f"{name}_{datetime.now():%Y%m%d_%H%M%S}"
    out.mkdir(parents=True, exist_ok=True)
    det = ch.detector()
    taken: list[np.ndarray] = []
    coverage = None
    prev, still_since, n = None, None, 0
    auto = True
    win = f"so101-cam {name}"
    print(
        f"Show the iPad board (full screen, brightness up, no lamp reflected in it) to the {name} camera.\n"
        "Move it around: all corners of the image, near and far, tilted left/right/up/down up to ~45 deg;\n"
        "hold each pose still for half a second. Views are taken automatically (green flash).\n"
        f"Aim for {TARGET_VIEWS}. space = take one now, a = auto on/off, q or Esc = finish."
    )
    while True:
        ok, frame = cap.read()
        if not ok:
            continue
        imgs = halves(frame, name)
        size = (imgs[0].shape[1], imgs[0].shape[0])
        if coverage is None:
            coverage = np.zeros((6, 8), int)
        views = [ch.detect(cv2.cvtColor(im, cv2.COLOR_BGR2GRAY), det) for im in imgs]
        main = views[0]
        now = time.perf_counter()
        still = False
        if (
            main is not None
            and prev is not None
            and len(prev.ids) == len(main.ids)
            and (prev.ids == main.ids).all()
        ):
            moved = np.linalg.norm(main.img - prev.img, axis=1).mean()
            if moved < STILL_PX:
                still_since = still_since or now
                still = now - still_since > STILL_S
            else:
                still_since = None
        else:
            still_since = None
        prev = main
        desc = None if main is None else pose_descriptor(main, size)
        novel = desc is not None and all(np.linalg.norm(desc - t) > NOVEL for t in taken)
        both = all(v is not None for v in views)
        key = cv2.waitKey(1) & 0xFF
        take = both and ((auto and still and novel) or key == ord(" "))
        if take:
            cv2.imwrite(str(out / f"{n:03d}.png"), frame)
            taken.append(desc)
            n += 1
            for x, y in main.img:
                coverage[min(int(y / size[1] * 6), 5), min(int(x / size[0] * 8), 7)] += 1
            still_since = None
            print(f"  view {n}: {len(main.ids)} corners", flush=True)
        # display: the left/only image, corners, coverage of the image by views taken
        disp = imgs[0].copy()
        for r in range(6):
            for c in range(8):
                if coverage[r, c]:
                    x0, y0 = int(c * size[0] / 8), int(r * size[1] / 6)
                    x1, y1 = int((c + 1) * size[0] / 8), int((r + 1) * size[1] / 6)
                    sub = disp[y0:y1, x0:x1]
                    disp[y0:y1, x0:x1] = (0.75 * sub + 0.25 * np.array([0, 160, 0])).astype(np.uint8)
        if main is not None:
            for x, y in main.img:
                cv2.circle(disp, (int(x), int(y)), 4, (0, 0, 255) if not both else (0, 200, 255), -1)
        status = (
            f"views {n}/{TARGET_VIEWS}  cells {int((coverage > 0).sum())}/48  "
            f"{'board ' + str(len(main.ids)) if main else 'no board'}"
            f"{'' if both or main is None else ' (other eye: none)'}  {'still' if still else ''}"
            f"{'' if novel or main is None else ' (pose taken)'}  auto {'on' if auto else 'off'}"
        )
        cv2.putText(disp, status, (10, 28), cv2.FONT_HERSHEY_SIMPLEX, 0.7, (0, 0, 0), 4)
        cv2.putText(disp, status, (10, 28), cv2.FONT_HERSHEY_SIMPLEX, 0.7, (255, 255, 255), 1)
        if take:
            disp[:] = (0.5 * disp + 0.5 * np.array([0, 255, 0])).astype(np.uint8)
        cv2.imshow(win, disp)
        if key in (ord("q"), 27):
            break
        if key == ord("a"):
            auto = not auto
    cap.release()
    cv2.destroyAllWindows()
    print(f"{n} views in {out}\nCalibrate with: uv run so101-cam calibrate {out}")
    return out


# -- calibration ---------------------------------------------------------------------------------------------
def load_views(folder: Path, name: str) -> tuple[list[list[ch.View]], tuple[int, int], list[str]]:
    """Per eye, the views detected in every image of `folder`; images where any eye misses the board are
    left out, so the eyes' lists stay paired."""
    det = ch.detector()
    eyes: list[list[ch.View]] = []
    files, size = [], None
    for f in sorted(folder.glob("*.png")):
        imgs = halves(cv2.imread(str(f)), name)
        vs = [ch.detect(cv2.cvtColor(im, cv2.COLOR_BGR2GRAY), det) for im in imgs]
        if any(v is None for v in vs):
            continue
        if not eyes:
            eyes = [[] for _ in vs]
        for e, v in zip(eyes, vs, strict=True):
            e.append(v)
        files.append(f.name)
        size = (imgs[0].shape[1], imgs[0].shape[0])
    return eyes, size, files


def calibrate_cmd(folders: list[Path]) -> None:
    """Calibrate from one or more capture folders of the same camera (views merged)."""
    folder = folders[0]
    name = folder.name.split("_")[0]
    if any(f.name.split("_")[0] != name for f in folders):
        raise SystemExit("all folders must be of the same camera")
    eyes, size, files = [], None, []
    for f in folders:
        e, sz, fl = load_views(f, name)
        if not e:
            continue
        eyes = e if not eyes else [a + b for a, b in zip(eyes, e, strict=True)]
        size, files = sz, files + [f"{f.name}/{x}" for x in fl]
    if not eyes or len(eyes[0]) < 10:
        raise SystemExit(f"only {len(eyes[0]) if eyes else 0} usable views in {folder}; take more")
    RESULTS.mkdir(parents=True, exist_ok=True)
    labels = ["left", "right"] if name == "zed" else [name]
    cals, md = {}, [f"# S3 intrinsics: {', '.join(f.name for f in folders)}", ""]
    md += [
        f"{len(files)} views with the board in every eye; ChArUco {ch.SQUARES_X} x {ch.SQUARES_Y}, "
        f"{ch.SQUARE_M * 1000:g} mm squares (iPad, {ch.IPAD_PPI:g} ppi); OpenCV, 5-parameter distortion.",
        "",
        "| Camera | Views used | RMS (px) | Cross-validated (px) | fx | fy | cx | cy "
        "| k1 | k2 | p1 | p2 | k3 |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]

    def row(label, intr, used, rms, cv, std=None):
        d = intr.to_dict()
        vals = [d["fx"], d["fy"], d["cx"], d["cy"]]
        cells = [
            f"{v:.1f}" if std is None else f"{v:.1f} +- {s:.1f}"
            for v, s in zip(vals, std if std is not None else vals, strict=True)
        ]
        dist = [f"{x:+.4f}" for x in d["dist_k1_k2_p1_p2_k3"]]
        return f"| {label} | {used} | {rms} | {cv} | " + " | ".join(cells + dist) + " |"

    for label, views in zip(labels, eyes, strict=True):
        cal = ch.calibrate(views, size)
        cv = ch.cross_validated_px(views, size)
        cals[label] = cal
        md.append(row(label, cal.intr, len(cal.used), f"{cal.rms_px:.3f}", f"{cv:.3f}", cal.std[:4]))
    out_yaml = {
        "source": [f.name for f in folders],
        "board": f"charuco {ch.SQUARES_X}x{ch.SQUARES_Y} {ch.SQUARE_M}",
    }
    for label, cal in cals.items():
        out_yaml[label] = cal.intr.to_dict() | {"rms_px": round(cal.rms_px, 4)}
    if name == "zed" and FACTORY.exists():
        fac = ch.read_zed_conf(FACTORY, "HD")
        out_yaml["use"] = "factory"  # S3: confirmed by our left eye and the triangulated square size
        out_yaml["factory"] = {
            "left": fac["left"].to_dict(),
            "right": fac["right"].to_dict(),
            "baseline_mm": fac["baseline_mm"],
            "t_mm": [float(x) for x in fac["t_mm"]],
            "rot_rx_cv_rz_rad": [float(x) for x in fac["rot_rad"]],
        }
        for label in labels:
            errs = [ch.reprojection_px(v, fac[label]) for v in eyes[labels.index(label)]]
            md.append(
                row(
                    f"{label}, factory",
                    fac[label],
                    len(errs),
                    f"{np.sqrt(np.mean(np.square(errs))):.3f}",
                    "-",
                )
            )
        md += ["", *stereo_report(eyes, size, cals, fac)]
    path = RESULTS / f"{name}_intrinsics.yaml"
    path.write_text(yaml.safe_dump(out_yaml, sort_keys=False))
    md += ["", f"Per-view RMS (px), first eye: {np.round(cals[labels[0]].per_view_px, 2).tolist()}", ""]
    report = RESULTS / f"{folders[-1].name}.md"
    report.write_text("\n".join(md))
    print("\n".join(md))
    print(f"Wrote {path} and {report}")


def stereo_report(eyes, size, cals, fac) -> list[str]:
    """Our stereo calibration (each eye's intrinsics fixed) against the factory's, and both checked by the
    board's own size: corners triangulated with the pair, distances between neighbours vs 25 mm."""
    obj = [v.obj.astype(np.float32) for v in eyes[0]]
    common = []
    for vl, vr in zip(*eyes, strict=True):
        ids = np.intersect1d(vl.ids, vr.ids)
        il = np.array([vl.img[list(vl.ids).index(i)] for i in ids], np.float32)
        ir = np.array([vr.img[list(vr.ids).index(i)] for i in ids], np.float32)
        common.append((ids, il, ir))
    obj = [ch.board().getChessboardCorners()[c[0]].astype(np.float32) for c in common]
    L, R = cals["left"].intr, cals["right"].intr
    rms, *_, Rm, T, _, _ = cv2.stereoCalibrate(
        obj,
        [c[1] for c in common],
        [c[2] for c in common],
        L.K,
        L.D,
        R.K,
        R.D,
        size,
        flags=cv2.CALIB_FIX_INTRINSIC,
    )
    rot = cv2.Rodrigues(Rm)[0].ravel()
    lines = [
        "| Stereo | RMS (px) | Baseline (mm) | T (mm) | Rotation (deg) | Square size by triangulation (mm) |",
        "|---|---:|---:|---|---|---:|",
    ]
    ours_sq = square_size_mm(common, L, R, Rm, T.ravel() * 1000)
    lines.append(
        f"| ours | {rms:.3f} | {np.linalg.norm(T) * 1000:.2f} | {np.round(T.ravel() * 1000, 2).tolist()} | "
        f"{np.round(np.degrees(rot), 3).tolist()} | {ours_sq:.3f} |"
    )
    Rf = cv2.Rodrigues(fac["rot_rad"].reshape(3, 1))[0]
    fac_sq = square_size_mm(common, fac["left"], fac["right"], Rf, fac["t_mm"])
    lines.append(
        f"| factory | - | {fac['baseline_mm']:.2f} | {np.round(fac['t_mm'], 2).tolist()} | "
        f"{np.round(np.degrees(fac['rot_rad']), 3).tolist()} | {fac_sq:.3f} |"
    )
    lines += [
        "",
        f"Square size: the board's {ch.SQUARE_M * 1000:g} mm squares measured by triangulating its corners "
        "with each calibration (median over all neighbouring pairs). The factory rotation is read as a "
        "rotation vector (RX, CV, RZ); its sign convention is not documented, so compare magnitudes.",
    ]
    return lines


def square_size_mm(common, L, R, Rm, t_mm) -> float:
    P1 = L.K @ np.hstack([np.eye(3), np.zeros((3, 1))])
    P2 = R.K @ np.hstack([Rm, np.asarray(t_mm, float).reshape(3, 1)])
    sizes = []
    for ids, il, ir in common:
        ul = cv2.undistortPoints(il.reshape(-1, 1, 2), L.K, L.D, P=L.K).reshape(-1, 2)
        ur = cv2.undistortPoints(ir.reshape(-1, 1, 2), R.K, R.D, P=R.K).reshape(-1, 2)
        X = cv2.triangulatePoints(P1, P2, ul.T, ur.T)
        X = (X[:3] / X[3]).T
        corners = ch.board().getChessboardCorners()[ids]
        for a in range(len(ids)):
            for b in range(a + 1, len(ids)):
                if abs(np.linalg.norm(corners[a] - corners[b]) - ch.SQUARE_M) < 1e-6:
                    sizes.append(np.linalg.norm(X[a] - X[b]))
    return float(np.median(sizes))


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("stage", choices=["board", "capture", "calibrate"])
    ap.add_argument("arg", nargs="*")
    a = ap.parse_args()
    if a.stage == "board":
        print(f"Wrote {write_board_page()}")
    elif a.stage == "capture":
        if len(a.arg) != 1 or a.arg[0] not in CAMERAS:
            raise SystemExit("so101-cam capture wrist|zed")
        capture(a.arg[0])
    else:
        if not a.arg:
            raise SystemExit("so101-cam calibrate captures/s3/<cam>_<time> [more folders of that camera]")
        calibrate_cmd([Path(x) for x in a.arg])


if __name__ == "__main__":
    main()

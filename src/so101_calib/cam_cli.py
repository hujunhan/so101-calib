"""so101-cam: S3, camera intrinsics from a ChArUco board on an iPad. No arm motion.

    so101-cam board                 write tools/ipad_charuco.html (the board, pixel for pixel at 264 ppi)
    so101-cam capture wrist|zed     live window: hold the iPad board in front of the camera in many poses;
                                    views are taken automatically when the board is still and the pose is
                                    new (space: take one now; q / Esc: finish) -> captures/s3/<cam>_<time>/
    so101-cam calibrate DIR [DIR..] intrinsics (folders merged) -> results/s3/<cam>_intrinsics.yaml
                                    and a report; for the ZED also the right eye, the stereo pair, and the
                                    factory calibration

Captures stay in the git-ignored captures/ (they show the room); results/ gets numbers only.
"""

import argparse
import base64
import time
from datetime import datetime
from pathlib import Path

import cv2
import numpy as np
import yaml

from so101_calib import charuco as ch

CAPTURES = Path("captures/s3")
RESULTS = Path("results/s3")
FACTORY = Path("captures/zed/zed_factory.conf")
TOOLS = Path(__file__).resolve().parents[2] / "tools"
TARGET_VIEWS = 15  # simulated: 15 views covering the image are as good as 30; coverage matters ~10x
STILL_PX, STILL_S = 1.0, 0.4  # the corners moved less than this (mean, px) for this long: no motion blur
NOVEL = 0.12  # a new view must differ this much from every view taken (pose descriptor distance)
CAMERAS = {
    # path key in so101-core devices.yaml, fourcc, size
    "wrist": ("wrist", "MJPG", (1280, 720)),
    "zed": ("zed", "YUYV", (2560, 720)),
    "zed_fhd": ("zed", "YUYV", (3840, 1080)),  # M3 records at FHD per eye
}


